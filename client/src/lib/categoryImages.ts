export function getBestCategoryImage(category: string, title: string, description: string = ""): string {
  const images = CATEGORY_IMAGES[category] || CATEGORY_IMAGES["Anders"];
  if (!images || images.length === 0) {
    return "https://images.unsplash.com/photo-1516450137517-162bfbeb8dba?q=80&w=1000";
  }

  const combinedText = `${title} ${description}`.toLowerCase();
  const subgroups = SUBCATEGORY_KEYWORDS[category];

  if (subgroups) {
    const scores: { groupIndex: number; score: number }[] = subgroups.map((group, index) => {
      const score = group.keywords.filter(kw => combinedText.includes(kw)).length;
      return { groupIndex: index, score };
    });
    scores.sort((a, b) => b.score - a.score);

    if (scores[0].score > 0) {
      const segmentSize = Math.floor(images.length / subgroups.length);
      const startIdx = scores[0].groupIndex * segmentSize;
      const endIdx = Math.min(startIdx + segmentSize, images.length);
      const segment = images.slice(startIdx, endIdx);
      if (segment.length > 0) {
        return segment[Math.floor(Math.random() * segment.length)];
      }
    }
  }

  return images[Math.floor(Math.random() * images.length)];
}

export function getCategoryImages(category: string): string[] {
  return CATEGORY_IMAGES[category] || CATEGORY_IMAGES["Anders"];
}

export function getDeterministicCategoryImage(category: string, eventId: number): string {
  const images = CATEGORY_IMAGES[category] || CATEGORY_IMAGES["Anders"] || [];
  if (!images || images.length === 0) {
    return "https://images.unsplash.com/photo-1516450137517-162bfbeb8dba?q=80&w=1000";
  }
  return images[Math.abs(eventId) % images.length];
}

export function getSmartAlternatives(category: string, title: string, description: string, currentImage: string): string[] {
  const categoryImages = getCategoryImages(category);
  const alternatives = categoryImages.filter(img => img !== currentImage);
  const shuffled = [...alternatives];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled.slice(0, 8);
}
